## Frequently asked questions

**What is the closest French town to Geneva?**

Gaillard and Ambilly touch the border at the Moillesulaz crossing, 5 km from the centre of Geneva, and central Annemasse is 8 km away. By train, Annemasse wins: Geneva Eaux-Vives in 7 minutes by Léman Express from the station.

**Where should I live on the French side if I work at CERN?**

In Saint-Genis-Pouilly, CERN's town, or in Ferney-Voltaire. By bus then tram, Cornavin is 45 minutes from Saint-Genis town hall. They are two of the most expensive towns on the border: €24.6 and €30.8/m² for a one- or two-room flat (Carte des loyers 2025).

**Which is the cheapest border town near Geneva?**

Among the towns in this guide, Ville-la-Grand (€17.1/m²) and Thonon-les-Bains (€18.9/m²) show the lowest one- or two-room asking rents (Carte des loyers, third quarter of 2025). Further out, Bons-en-Chablais and La Roche-sur-Foron drop below €19/m² while keeping a Léman Express station.

**Can you live on the French side without a car?**

Yes, in Annemasse, Ville-la-Grand and Ambilly: Léman Express every 10 minutes at rush hour, tram 17, the Voie Verte by bike. It is more constraining in Saint-Julien, Ferney or Saint-Genis (bus) and hard day to day in Divonne or Gex. Many of our residents do not own a car.

**Haute-Savoie or Ain: what does it change?**

For an employee of the canton of Geneva, nothing on taxes or health insurance. Haute-Savoie (Annemasse, Saint-Julien, Thonon) looks towards the left bank and the centre; the Ain (Ferney, Saint-Genis, Divonne) towards the airport, the international organisations and CERN. Pick your employer's side, not the other way round.

**Which French towns are on the Swiss border, beyond Geneva?**

Saint-Louis and Huningue opposite Basel, Pontarlier and Morteau opposite the canton of Neuchâtel and the Vaud Jura, Évian and Thonon opposite Lausanne across the lake. This guide only covers the Geneva basin, by far the largest.
