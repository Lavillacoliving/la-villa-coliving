## When it's not the right choice

If you go out late in Geneva several nights a week, the last train will remind you of the border: read [our Switzerland-or-France comparison](/en/blog/s-installer-a-geneve-expatrie-cote-suisse-ou-cote-france). If you arrive as a family with two cars, Vétraz-Monthoux, Cranves-Sales or the Pays de Gex beat central Annemasse. If your budget is really tight, the Chablais and the Arve valley win, provided you accept a train every 30 minutes. And if you are searching from afar, pay nothing before a visit: [cross-border housing scams](/en/blog/arnaques-logement-frontalier-geneve-eviter) target exactly the people in a hurry.

