## How we ranked these towns

Four criteria, the same for every town, and the sources are in the text.

1. **Door-to-door commute, not kilometres.** Read on Google Maps on a Monday, arriving at 8:30, from the town hall to a named Geneva station or stop, by public transport. No driving times: the border crossing at rush hour looks nothing like any displayed time.
2. **The official asking rent.** The French Housing Ministry's [Carte des loyers](https://www.data.gouv.fr/datasets/693aa2feed1bf4da603faa49/) (2025 edition, ANIL) gives, town by town, a rent per m² including charges for an unfurnished one- or two-room flat put on the market in the third quarter of 2025: same source everywhere, so comparable.
3. **Life without a car.** A Léman Express station or a tram 17 stop within walking distance: no customs queue, no parking in Geneva.
4. **What you do in the evening.** A lively centre, a market, a lake, or a dormitory town: we say which.

