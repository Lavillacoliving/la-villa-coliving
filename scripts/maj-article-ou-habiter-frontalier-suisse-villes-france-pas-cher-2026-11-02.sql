Dans l'Ain, à côté de l'aéroport et du quartier des Nations. Un bus TPG direct met Cornavin à une quarantaine de minutes porte-à-porte depuis la mairie (lundi, 8 h 30). Centre historique agréable, marché le samedi, beaucoup d'anglophones. Le revers : le loyer le plus élevé de ce guide, 30,8 €/m² en T1-T2, soit ≈ 1 140 € pour 37 m², et un marché saturé.

**Pour qui ?** ONU, OMS, CICR, aéroport. Pour le CERN, regarde d'abord Saint-Genis-Pouilly.

## 6. Thonon-les-Bains : le lac, le vrai budget, et le train quand même

À 35 km, Thonon est la ville de ce guide où un studio redevient abordable : 18,9 €/m² en T1-T2, soit ≈ 700 € pour 37 m², avec le lac, un port et un centre animé. Le Léman Express y passe : Genève-Eaux-Vives en 43 minutes de train, toutes les 30 minutes en pointe, soit 50 minutes porte-à-porte (horaire 2026). La navette CGN relie Lausanne, pas Genève.

**Pour qui ?** Qui échange près de 1 h 30 de train par jour contre un loyer nettement plus bas et le lac.

## 7. Divonne-les-Bains : le haut de gamme du Pays de Gex

Casino, golf, thermes, un lac, et la Suisse vaudoise à côté. En transports publics, il faut un bus jusqu'à Coppet puis le train : Cornavin en 50 minutes porte-à-porte depuis la mairie (lundi, 8 h 30). Loyer d'annonce T1-T2 : 30,3 €/m², soit ≈ 1 120 € pour 37 m².

**Pour qui ?** Familles en voiture, ou qui travaille à Nyon ou près de Coppet.

