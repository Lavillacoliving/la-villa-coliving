## What the town does not change: taxes, health insurance, permit

- **Taxes.** As an employee in the canton of Geneva, you are taxed at source in Geneva whether you live in Haute-Savoie or in the Ain, then you file in France with no double taxation ([our cross-border tax guide](/en/blog/fiscalite-frontalier-geneve-impots-2026)). The one exception: an employer in the canton of Vaud, and you pay in France.
- **Health insurance.** LAMal or French insurance, the choice is made within three months of starting the job, whatever your town: [LAMal or CMU, the comparison](/en/blog/assurance-sante-frontalier-lamal-cmu-budget).
- **The G permit.** Tied to your job, not your address, as long as you go home at least once a week: [the G permit guide](/en/blog/permis-g-frontalier-geneve).

What really changes with the town: the rent, the commute and its cost, priced in [the true cost of cross-border transport](/en/blog/cout-transport-frontalier-geneve-2026).

