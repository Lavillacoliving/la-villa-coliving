## Questions fréquentes

**Quelle est la ville française la plus proche de Genève ?**

Gaillard et Ambilly touchent la frontière à la douane de Moillesulaz, à 5 km du centre de Genève, et le centre d'Annemasse est à 8 km. En train, c'est Annemasse qui gagne : Genève-Eaux-Vives en 7 minutes de Léman Express depuis la gare.

**Où habiter côté France quand on travaille au CERN ?**

À Saint-Genis-Pouilly, la commune du CERN, ou à Ferney-Voltaire. En bus puis tram, Cornavin est à 45 minutes depuis la mairie de Saint-Genis. Ce sont deux des communes les plus chères de la frontière : 24,6 et 30,8 €/m² en T1-T2 (Carte des loyers 2025).

**Quelle est la ville frontalière la moins chère près de Genève ?**

Parmi les villes de ce guide, Ville-la-Grand (17,1 €/m²) et Thonon-les-Bains (18,9 €/m²) affichent les loyers d'annonce T1-T2 les plus bas (Carte des loyers, 3e trimestre 2025). Plus loin, Bons-en-Chablais et La Roche-sur-Foron descendent sous 19 €/m² en gardant une gare du Léman Express.

**Peut-on vivre côté France sans voiture ?**

Oui, à Annemasse, Ville-la-Grand et Ambilly : Léman Express toutes les 10 minutes en pointe, tram 17, Voie Verte à vélo. C'est plus contraignant à Saint-Julien, Ferney ou Saint-Genis (bus) et difficile au quotidien à Divonne ou Gex.

**Haute-Savoie ou Ain : ça change quoi ?**

Pour un salarié du canton de Genève, rien côté impôts ni assurance. La Haute-Savoie (Annemasse, Saint-Julien, Thonon) regarde vers la rive gauche et le centre ; l'Ain (Ferney, Saint-Genis, Divonne) vers l'aéroport, les organisations internationales et le CERN. Choisis le département de ton employeur, pas l'inverse.

**Quelles villes françaises sont à la frontière suisse, au-delà de Genève ?**

Saint-Louis et Huningue face à Bâle, Pontarlier et Morteau face au canton de Neuchâtel et au Jura vaudois, Évian et Thonon face à Lausanne par le lac. Ce guide ne couvre que le bassin de Genève, de loin le plus gros.
