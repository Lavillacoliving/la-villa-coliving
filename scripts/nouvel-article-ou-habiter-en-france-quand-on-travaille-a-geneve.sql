## Questions fréquentes

**Où est-il préférable d'habiter pour un frontalier près de Genève ?**

Là où ton trajet est simple : près d'une gare du Léman Express ou d'un arrêt du tram 17 si tu n'as pas de voiture. Pour un poste aux Eaux-Vives, à Champel ou dans le centre, vise Annemasse, Ville-la-Grand ou Ambilly ; pour les Nations, l'aéroport ou le CERN, Ferney-Voltaire et le Pays de Gex.

**Est-il possible de vivre en France et de travailler à Genève ?**

Oui : c'est le statut de frontalier, avec le permis G. Ressortissant de l'UE ou de l'AELE, tu déposes la demande en ligne auprès de l'OCPM avant ton premier jour de travail, et tu rentres chez toi, côté France, au moins une fois par semaine. [Notre guide pour vivre en France et travailler à Genève](/blog/living-in-france-working-in-geneva) détaille la fiscalité, la santé et le transport.

**Peut-on vivre côté France sans voiture quand on travaille à Genève ?**

Oui, si tu choisis ton logement autour d'une gare du Léman Express ou d'un arrêt du tram 17. Depuis la gare d'Annemasse, le Léman Express rejoint Genève-Eaux-Vives en 7 minutes et Cornavin en 23 minutes, sans changement.

**Annemasse ou Ville-la-Grand ?**

Annemasse pour la vie de ville et la gare au pied de chez toi ; Ville-la-Grand pour des rues pavillonnaires plus calmes, avec la gare d'Annemasse accessible à pied ou à vélo. Si tu hésites, [les quartiers d'Annemasse selon ton profil](/blog/quartiers-annemasse-ou-vivre-selon-profil) t'aident à trancher.

**Combien de temps pour aller à Genève depuis Annemasse ?**

En Léman Express, 7 minutes jusqu'à Genève-Eaux-Vives et 23 minutes jusqu'à Cornavin, sans changement. Porte-à-porte, depuis un logement à 10 minutes à pied de la gare, compte 20 minutes jusqu'aux Eaux-Vives.

**Où habiter quand on travaille aux Nations ?**

Côté France, Ferney-Voltaire et le Pays de Gex sont du bon côté de Genève : depuis Ferney, le bus rejoint le centre de Genève en 20 minutes. Depuis Annemasse, le Léman Express t'amène à Cornavin en 23 minutes, puis il reste la fin du trajet en tram ou en bus.

