## FAQ

**What is the closest French town to Geneva?**

Several French towns share a border with the canton of Geneva: Ambilly and Ville-la-Grand, next to Annemasse, on the east side; Ferney-Voltaire to the north; Saint-Julien-en-Genevois to the south-west. "Closest" matters less than your commute: pick the one on the same side of Geneva as your office.

**Can you live on the French side without a car?**

Yes, if you choose a place around a Léman Express station or a tram 17 stop. From Annemasse station, the Léman Express reaches Geneva Eaux-Vives in 7 minutes and Cornavin in 23 minutes, with no change.

**Is Annemasse a good place to live if you work in Geneva?**

Yes, especially if you work in Eaux-Vives, Champel or the centre: the station puts you on the Léman Express, and daily life is on foot. For a job at CERN or the airport, the other side of Geneva is a better fit. [Living in Annemasse when you work in Geneva](/en/blog/vivre-a-annemasse-quand-on-travaille-a-geneve) covers the details.

**How far is Annemasse from the Geneva border?**

Very close: Annemasse's neighbours, Ambilly and Ville-la-Grand, share a border with the canton of Geneva. From Annemasse station, the Léman Express reaches Geneva Eaux-Vives in 7 minutes; from a place 10 minutes' walk from the station, allow 20 minutes door to door.

**Ferney-Voltaire or Annemasse: which side of Geneva?**

The side your office is on. Ferney-Voltaire for the UN district, the airport and CERN; Annemasse for Eaux-Vives, Champel, Cornavin and the centre, by Léman Express.

**Do you need to live in Switzerland to get a permit?**

No. The G permit is exactly that: as an EU or EFTA national, you work in Geneva and live in a neighbouring country, returning home at least once a week, and you file the application online with the OCPM before your first day at work. [Our guide to living in France and working in Geneva](/en/blog/living-in-france-working-in-geneva) covers tax, health insurance and transport.

