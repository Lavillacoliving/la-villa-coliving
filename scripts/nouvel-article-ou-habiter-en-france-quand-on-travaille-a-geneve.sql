## Profil 5 — Tu viens pour 6 à 12 mois (mission, CDD, stage, période d'essai)

Cherche du meublé, sans durée minimale et avec un préavis court : une période d'essai qui tourne court ne doit pas te coûter un an de loyer.

- **Le bail meublé classique** dure un an, et tu peux le quitter à tout moment avec un mois de préavis (loi du 6 juillet 1989, article 25-8).
- **Le bail mobilité**, de 1 à 10 mois, est réservé aux personnes en formation, en stage, en mission temporaire ou en mutation : il ne se renouvelle pas, et le bailleur ne peut pas demander de dépôt de garantie (même loi, articles 25-12 à 25-18).
